#!/usr/bin/env python3
"""Generates deterministic FileVault unlock test data.

The generated encryption context fixtures contain a known volume master key
wrapped by the same KEK with different credentials. They are intentionally
small and are used to test the credential and AES Key Unwrap handling without
requiring a full disk image.

This script requires the cryptography module.
"""

import argparse
import base64
import hashlib
import os
import struct

from cryptography.hazmat.primitives.keywrap import aes_key_wrap


USER_PASSWORD = b"user-TEST"
RECOVERY_KEY = b"AAAA-BBBB-CCCC-DDDD-EEEE-FFFF"
VOLUME_MASTER_KEY = bytes(range(16))
KEK = bytes.fromhex("00112233445566778899aabbccddeeff")
NUMBER_OF_ITERATIONS = 1000
WRAPPED_KEK_IV = b"\xa6" * 8


def create_passphrase_wrapped_kek(passphrase, salt):
    """Creates a 284-byte PassphraseWrappedKEKStruct."""
    passphrase_key = hashlib.pbkdf2_hmac(
        "sha256", passphrase, salt, NUMBER_OF_ITERATIONS, 16
    )
    wrapped_kek = aes_key_wrap(passphrase_key, KEK)

    data = bytearray(284)
    struct.pack_into("<II", data, 0, 3, 16)
    data[8:24] = salt
    struct.pack_into("<II", data, 24, 0x00000010, 24)
    data[32:56] = wrapped_kek
    struct.pack_into("<I", data, 168, NUMBER_OF_ITERATIONS)
    return bytes(data)


def create_kek_wrapped_volume_key():
    """Creates a 256-byte KEKWrappedVolumeKeyStruct."""
    data = bytearray(256)
    struct.pack_into("<II", data, 0, 2, 24)
    data[8:32] = aes_key_wrap(KEK, VOLUME_MASTER_KEY)
    return bytes(data)


def create_encryption_context(credentials):
    """Creates an XML encryption context plist."""
    crypto_users = []
    for index, (credential_type, passphrase) in enumerate(credentials):
        salt = hashlib.sha256(
            credential_type.encode("ascii") + b"-unlock-test-salt"
        ).digest()[:16]
        wrapped_kek = create_passphrase_wrapped_kek(passphrase, salt)
        wrapped_kek_base64 = base64.b64encode(wrapped_kek).decode("ascii")
        crypto_users.append(
            "<dict ID=\"{0:d}\">"
            "<key>PassphraseWrappedKEKStruct</key>"
            "<data ID=\"{1:d}\">{2:s}</data>"
            "<key>UserType</key>"
            "<integer size=\"32\" ID=\"{3:d}\">0x10000001</integer>"
            "<key>WrapVersion</key>"
            "<integer size=\"32\" ID=\"{4:d}\">0x1</integer>"
            "</dict>".format(
                index * 4 + 3,
                index * 4 + 4,
                wrapped_kek_base64,
                index * 4 + 5,
                index * 4 + 6,
            )
        )

    wrapped_volume_key_base64 = base64.b64encode(
        create_kek_wrapped_volume_key()
    ).decode("ascii")

    return (
        "<dict ID=\"0\">"
        "<key>com.apple.corestorage.lvf.encryption.context</key>"
        "<dict ID=\"1\">"
        "<key>CryptoUsers</key>"
        "<array ID=\"2\">{0:s}</array>"
        "<key>WrappedVolumeKeys</key>"
        "<array>"
        "<dict>"
        "<key>BlockAlgorithm</key><string>None</string>"
        "<key>KEKWrappedVolumeKeyStruct</key><data></data>"
        "</dict>"
        "<dict>"
        "<key>BlockAlgorithm</key><string>AES-XTS</string>"
        "<key>KEKWrappedVolumeKeyStruct</key>"
        "<data>{1:s}</data>"
        "</dict>"
        "</array>"
        "</dict>"
        "</dict>\n"
    ).format("".join(crypto_users), wrapped_volume_key_base64)


def create_c_header(data, variable_name):
    """Creates a C header with a byte array for the test data."""
    include_guard = "_{0}_H".format(variable_name.upper())
    data_lines = []
    for offset in range(0, len(data), 16):
        data_line = ", ".join(
            "0x{0:02x}".format(byte_value) for byte_value in data[offset : offset + 16]
        )
        data_lines.append("    {0:s}".format(data_line))

    return (
        "/* Generated by generate_unlock_test_data.py, do not edit manually. */\n"
        "#if !defined({0:s})\n"
        "#define {0:s}\n\n"
        "static const uint8_t {4:s}[ {1:d} ] = {{\n"
        "{2:s}\n"
        "}};\n"
        "#define {3:s}_SIZE {1:d}\n\n"
        "#endif /* !defined({0:s}) */\n"
    ).format(
        include_guard,
        len(data),
        ",\n".join(data_lines),
        variable_name.upper(),
        variable_name,
    )


def main():
    """Generates the unlock test data."""
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--output-directory",
        default=os.path.join(os.path.dirname(__file__), "data"),
    )
    options = parser.parse_args()

    os.makedirs(options.output_directory, exist_ok=True)

    fixtures = {
        "encryption_context_plist.user_password": [
            ("user", USER_PASSWORD)
        ],
        "encryption_context_plist.recovery_key": [
            ("recovery", RECOVERY_KEY)
        ],
        "encryption_context_plist.mixed_credentials": [
            ("user", USER_PASSWORD),
            ("recovery", RECOVERY_KEY),
        ],
    }
    for filename, credentials in fixtures.items():
        data = create_encryption_context(credentials).encode("ascii")
        file_path = os.path.join(options.output_directory, filename)
        with open(file_path, "wb") as file_object:
            file_object.write(data)

        variable_name = "fvde_test_{0:s}".format(
            filename.replace(".", "_").replace("-", "_")
        )
        with open(file_path + ".h", "w", encoding="ascii") as file_object:
            file_object.write(create_c_header(data, variable_name))

        print("Generated: {0:s}".format(file_path))


if __name__ == "__main__":
    main()
